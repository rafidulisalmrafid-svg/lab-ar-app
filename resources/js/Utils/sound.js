// Web Audio API Synthesizer for High-Tech UI Clicks & Hover Sound FX
let audioCtx = null;
let soundEnabled = false;

export function toggleAudio(forceState) {
  if (typeof window === 'undefined') return false;
  soundEnabled = forceState !== undefined ? forceState : !soundEnabled;
  if (soundEnabled && !audioCtx) {
    try {
      const AudioContext = window.AudioContext || window.webkitAudioContext;
      audioCtx = new AudioContext();
    } catch (e) {
      console.warn('AudioContext not supported', e);
    }
  }
  return soundEnabled;
}

export function isAudioEnabled() {
  return soundEnabled;
}

export function playUiClick() {
  if (!soundEnabled || !audioCtx) return;
  try {
    if (audioCtx.state === 'suspended') {
      audioCtx.resume();
    }
    const osc = audioCtx.createOscillator();
    const gain = audioCtx.createGain();
    osc.type = 'sine';
    osc.frequency.setValueAtTime(880, audioCtx.currentTime);
    osc.frequency.exponentialRampToValueAtTime(1760, audioCtx.currentTime + 0.05);

    gain.gain.setValueAtTime(0.04, audioCtx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.001, audioCtx.currentTime + 0.05);

    osc.connect(gain);
    gain.connect(audioCtx.destination);

    osc.start();
    osc.stop(audioCtx.currentTime + 0.05);
  } catch (e) {
    // silent fallback
  }
}

